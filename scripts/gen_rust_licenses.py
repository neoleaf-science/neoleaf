#!/usr/bin/env python3
"""Lists the Rust dependencies (name, version, license, source) of the server and of the local agent.

  static/licenses/rust-agent.txt    the agent is distributed as a binary: this is its notices list
  static/licenses/rust-server.txt   the server (runs only on our infrastructure), listed for transparency

Uses `cargo metadata` (the `license` field of each crate). It is a list, not the license texts: the texts are in each crate's
source on crates.io. Usage:  python3 scripts/gen_rust_licenses.py
"""
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def crates(manifest_dir):
    out = subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=manifest_dir, check=True,
                         capture_output=True, text=True).stdout
    meta = json.loads(out)
    own = set(meta["workspace_members"])
    rows = []
    for p in meta["packages"]:
        if p["id"] in own:
            continue
        rows.append((p["name"], p["version"], p.get("license") or "see the crate source", p.get("repository") or f"https://crates.io/crates/{p['name']}"))
    return sorted(rows)


def write(path, title, rows):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"{title}\n{len(rows)} third-party crates. Generated by scripts/gen_rust_licenses.py from `cargo metadata`.\n")
        f.write("Format: name version | license (SPDX) | source\n\n")
        for name, ver, lic, repo in rows:
            f.write(f"{name} {ver} | {lic} | {repo}\n")
    print(path, len(rows))


write(os.path.join(ROOT, "static/licenses/rust-agent.txt"), "NeoLeaf local agent: Rust dependencies", crates(os.path.join(ROOT, "agent")))
write(os.path.join(ROOT, "static/licenses/rust-server.txt"), "NeoLeaf server: Rust dependencies", crates(ROOT))
