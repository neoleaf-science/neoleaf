#!/usr/bin/env python3
"""Generates docs/js-globals.md: the contract between the editor scripts (classic scripts that share one global scope).

For every script in static/js it lists the names it puts on `window` and the top-level functions and variables it declares,
and which other scripts use each name. Run it after changing the scripts: `python3 scripts/js_globals.py`.
"""
import re, glob, os, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP = {'context-index.js'}   # data files (the i18n-<code>.js translation files are skipped too, see below)


def strip(src):
    """Removes comments and the contents of strings so names inside them are not counted."""
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    src = re.sub(r'(?m)^\s*//.*$', '', src)
    src = re.sub(r'(?<![:"\'])//[^\n]*', '', src)
    return re.sub(r'(["\'`])(?:\\.|(?!\1)[^\\\n])*\1', '""', src)


def main():
    files = sorted(f for f in glob.glob(os.path.join(ROOT, 'static/js/*.js')) if os.path.basename(f) not in SKIP and not re.match(r'i18n-[a-z]+\.js$', os.path.basename(f)))
    info = {}
    for f in files:
        name = os.path.basename(f)
        raw = open(f, encoding='utf-8').read()
        code = strip(raw)
        win = sorted(set(re.findall(r'\bwindow\.([A-Za-z_$][\w$]*)\s*=(?!=)', code)))
        iife = code.lstrip().startswith('(') or re.search(r'^\(function', code, re.M) is not None
        top_fn = re.findall(r'^(?:async\s+)?function\s+([A-Za-z_$][\w$]*)', code, re.M)
        top_var = re.findall(r'^(?:let|const|var)\s+([A-Za-z_$][\w$]*)', code, re.M)
        info[name] = {'window': win, 'fn': top_fn, 'var': top_var, 'iife': bool(iife and not top_fn and not top_var)}
    # who uses a name
    texts = {os.path.basename(f): strip(open(f, encoding='utf-8').read()) for f in files}
    out = ['# Editor scripts: global names (generated)', '',
           'Generated by `python3 scripts/js_globals.py`; do not edit by hand. The editor scripts are **classic scripts that share one global scope** (no bundler, no ES modules).',
           'The load order is the `<script>` order in `src/views/editor_page/script.rs`. A script may call the names of the scripts loaded before it at load time and',
           'the names of any script at run time. "Used by" lists the other scripts that mention the name.', '']
    for name in sorted(info):
        d = info[name]
        names = [('window.' + n) for n in d['window']] + d['fn'] + d['var']
        if not names:
            continue
        out.append(f'## `{name}`')
        out.append('')
        if d['iife']:
            out.append('Wrapped in an IIFE: it only exposes the `window.*` names below.')
            out.append('')
        out.append('| Name | Kind | Used by |')
        out.append('|---|---|---|')
        def row(label, kind, ident):
            users = sorted(o for o in texts if o != name and re.search(r'(?<![\w$.])' + re.escape(ident) + r'\b', texts[o]))
            out.append(f'| `{label}` | {kind} | {", ".join(users) if users else "(only itself)"} |')
        for n in d['window']:
            row('window.' + n, 'window', n)
        for n in d['fn']:
            row(n, 'function', n)
        for n in d['var']:
            row(n, 'variable', n)
        out.append('')
    path = os.path.join(ROOT, 'docs', 'js-globals.md')
    open(path, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    total = sum(len(i['window']) + len(i['fn']) + len(i['var']) for i in info.values())
    print(f'{path}: {len(info)} scripts, {total} global names')


if __name__ == '__main__':
    main()
