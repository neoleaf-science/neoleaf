#!/usr/bin/env python3
"""Pins the spell check dictionaries and writes static/js/spellcheck-dicts.js.

NeoLeaf hosts no dictionary. The browser downloads each one from the LibreOffice dictionaries repository at a fixed commit (raw.githubusercontent.com,
with jsDelivr as a mirror), checks the SHA-256 written here and keeps it in the browser only. This script downloads the files of a commit, computes
size and SHA-256 and writes the table that the page (labels, sizes) and the worker (addresses, hashes) read.

  python3 scripts/pin_dictionaries.py [commit]        # default: the current master of LibreOffice/dictionaries

To add a language: add it to DICTS (id, label, files, license, readme), run this, then see static/js/spellcheck.js (SUPPORTED, LANG_NAMES, STOPWORDS),
the project setting (src/views/editor_page/modals.rs, static/js/project-store.js) and the license notices.
"""
import hashlib
import json
import os
import subprocess
import sys
import urllib.request

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "static/js/spellcheck-dicts.js")
REPO = "LibreOffice/dictionaries"

# id (the BCP 47 tag the editor uses), name in its own language, folder and base name in the repository, encoding of the files, license as the
# README declares it, and the README that says so.
DICTS = [
    dict(id="pt-BR", label="Português (Brasil)", dir="pt_BR", base="pt_BR", encoding="utf-8",
         license="LGPL-3.0 and MPL (the README does not give the MPL version)", readme="pt_BR/README_pt_BR.txt",
         authors="Raimundo Santos Moura and the VERO contributors"),
    dict(id="pt-PT", label="Português (Portugal)", dir="pt_PT", base="pt_PT", encoding="utf-8",
         license="GPL 2, LGPL 2.1 or MPL 1.1 (in that order of preference)", readme="pt_PT/README_pt_PT.txt",
         authors="José João Almeida and the contributors named in the README"),
    dict(id="en-US", label="English (US)", dir="en", base="en_US", encoding="utf-8",
         license="SCOWL license (MIT-like, with BSD and other notices)", readme="en/README_en_US.txt",
         authors="Kevin Atkinson and the other holders named in the README"),
    dict(id="en-GB", label="English (UK)", dir="en", base="en_GB", encoding="utf-8",
         license="LGPL", readme="en/README_en_GB.txt", authors="the authors named in the README"),
    dict(id="es-ES", label="Español", dir="es", base="es_ES", encoding="utf-8",
         license="GPL 3 or later, LGPL 3 or later or MPL 1.1 or later", readme="es/README_hunspell_es.txt",
         authors="the authors named in the README"),
    dict(id="fr-FR", label="Français", dir="fr_FR/dictionaries", base="fr", encoding="utf-8",
         license="MPL 2.0", readme="fr_FR/dictionaries/README_dict_fr.txt", authors="the authors named in the README"),
    dict(id="it-IT", label="Italiano", dir="it_IT", base="it_IT", encoding="utf-8",
         license="GPL 3", readme="it_IT/README_it_IT.txt", authors="LibreItalia (Marina Latini) and other authors"),
    dict(id="de-DE", label="Deutsch", dir="de", base="de_DE_frami", encoding="iso-8859-1",
         license="GPL 2 or 3", readme="de/README_de_DE_frami.txt", authors="the igerman98 and frami authors"),
]


def fetch(url):
    with urllib.request.urlopen(url, timeout=120) as r:
        return r.read()


def main():
    commit = sys.argv[1] if len(sys.argv) > 1 else json.loads(
        subprocess.run(["gh", "api", f"repos/{REPO}/commits/master"], check=True, capture_output=True, text=True).stdout)["sha"]
    raw = f"https://raw.githubusercontent.com/{REPO}/{commit}/"
    out = []
    for d in DICTS:
        files = []
        for ext in ("aff", "dic"):
            path = f"{d['dir']}/{d['base']}.{ext}"
            data = fetch(raw + path)
            files.append({"ext": ext, "path": path, "size": len(data), "sha256": hashlib.sha256(data).hexdigest()})
            print(f"{d['id']:6} {path:36} {len(data):>9} bytes  {files[-1]['sha256'][:16]}")
        out.append({"id": d["id"], "label": d["label"], "encoding": d["encoding"], "license": d["license"], "authors": d["authors"],
                    "readme": d["readme"], "files": files})
    table = {
        "commit": commit,
        "raw": raw,
        "mirror": f"https://cdn.jsdelivr.net/gh/{REPO}@{commit}/",
        "list": out,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/pin_dictionaries.py: do not edit by hand.\n")
        f.write("// The spell check dictionaries: where the browser downloads them from (nothing is hosted by NeoLeaf) and the SHA-256 it must see.\n")
        f.write("self.NEOLEAF_DICTS = " + json.dumps(table, ensure_ascii=False, indent=2) + ";\n")
    print("wrote", OUT, "at commit", commit)


main()
