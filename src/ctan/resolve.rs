use super::*;

/// Ensures the TeX Live index is on disk right at server startup, in the background. With the file already built (TeX Live 2023 is
/// frozen, so only the first time) startup downloads and processes nothing.
pub async fn warm_index() {
    // The index files used to have Portuguese names; drop the old copies (about 35 MB) once the new ones take over.
    for old in [
        "indice-arquivos.idx",
        "indice-minusculas.idx",
        "indice-sha512.idx",
    ] {
        let _ = std::fs::remove_file(cache_dir().join(old));
    }
    if let Err(e) = ensure_index().await {
        eprintln!(
            "TeX Live index did not load at startup: {e} (will be retried on the first request)"
        );
    }
}

pub(super) fn lookup_package(dir: &std::path::Path, base: &str) -> Option<String> {
    let p = index_paths(dir);
    if let Some(pkg) = lookup(&p.files, KEY_W, PKG_W, base) {
        return Some(pkg);
    }
    // If the file came without an extension (e.g. "FiraSans-Book" or "FiraSans"):
    for ext in EXTS {
        if let Some(pkg) = lookup(&p.files, KEY_W, PKG_W, &format!("{base}.{ext}")) {
            return Some(pkg);
        }
    }
    // Case-insensitive lookup
    let lb = base.to_ascii_lowercase();
    if let Some(pkg) = lookup(&p.lower, KEY_W, PKG_W, &lb) {
        return Some(pkg);
    }
    EXTS.iter()
        .find_map(|ext| lookup(&p.lower, KEY_W, PKG_W, &format!("{lb}.{ext}")))
}

/// Finds which TeX Live package contains a file (`lmodern.sty` -> `lm`, `FiraSans-Book.otf` -> `fira`).
pub async fn package_for_file(file: &str) -> Result<Option<String>, String> {
    // odd name (generated by macros, with spaces or symbols): it does not exist in TeX Live; it must not break whoever asks
    let Some(base) = safe_basename(file) else {
        return Ok(None);
    };
    ensure_index().await?;
    let dir = cache_dir();
    tokio::task::spawn_blocking(move || lookup_package(&dir, &base))
        .await
        .map_err(|e| e.to_string())
}
