// pdfLaTeX compilation in the browser (WebAssembly).
// Classic script: shares the page's global scope with the other editor scripts (see editor_page.rs for the load order).

// Builds the shared state of one WASM compilation (names, previous build, pass bookkeeping).
function wasmBuildState(files, main, sw) {
  const base = main.replace(/\.tex$/i, '');
  const openEntry = ((window.FT && FT.entries()) || []).find(e => e.id === currentFileId);
  const fastOnly = fastMode ? chapterOfOpenFile(files.get(main), openEntry && openEntry.path) : null;
  // TeX writes the PDF in the working folder with the file name (without subfolders): samples/a.tex -> a.pdf
  const pdfName = base + '.pdf';
  const jobPdf = base.split('/').pop() + '.pdf';
  const findPdf = outputs => outputGet(outputs, pdfName) || outputGet(outputs, jobPdf);
  const logs = [];
  const buildKey = main;
  const prev = (!forceCleanBuild && lastBuild && lastBuild.key === buildKey) ? lastBuild : null;
  forceCleanBuild = false;
  const jobname = base.split('/').pop();
  const helperFiles = new Map(); // generated by BibTeX (.bbl): they must go into all the following passes
  const bibHash = hashFiles(files, /\.(bib|bst)$/i);
  if (prev && prev.bbl) helperFiles.set(jobname + '.bbl', prev.bbl);
  return {
    files, main, sw, base, fastOnly, findPdf, logs, result: null, buildKey, prev,
    extra: new Map(prev ? prev.extra : []), // files generated in the previous pass (.aux, .toc, .bbl...)
    passes: 0, lastPassLog: '', usedCiteKey: prev ? prev.citeKey : '', jobname,
    bibtexRan: false, bibLogText: '', helperFiles, bibHash
  };
}

// Type 1 fonts that come with an extra package (for example roboto) are activated by the package's .map file. A normal TeX Live
// enables it with updmap, which does not exist in the browser, so the .map files that came with the project are loaded here.
function pdfMapPrefix(files) {
  return [...files.keys()].filter(n => /^[A-Za-z0-9_.+-]+\.map$/.test(n)).sort().map(n => `\\pdfmapfile{+${n}}`).join('');
}

// Runs one pdfTeX pass over the project files plus the auxiliary files of the previous pass.
async function wasmRunPass(b, engine, pass, draft) {
  const { files, main, fastOnly, jobname } = b;
  const input = [...files.entries()].map(([path, content]) => ({ path, content }));
  for (const [path, content] of b.extra) if (!files.has(path)) input.push({ path, content });
  const args = ['-synctex=1', ...(draft ? ['-draftmode'] : [])];
  let mainArg = main;
  if (fastOnly) { mainArg = `\\includeonly{${fastOnly}}\\input{${main}}`; args.push('-jobname=' + jobname); }
  if (forceLmodern) {
    mainArg = `\\RequirePackage{lmodern}${fastOnly ? `\\includeonly{${fastOnly}}` : ''}\\input{${main}}`;
    if (!args.includes('-jobname=' + jobname)) args.push('-jobname=' + jobname);
  }
  const maps = pdfMapPrefix(files);
  if (maps) {
    mainArg = maps + (mainArg.startsWith('\\') ? mainArg : `\\input{${mainArg}}`);
    if (!args.includes('-jobname=' + jobname)) args.push('-jobname=' + jobname);
  }
  return engine.compile({ mainTex: mainArg, files: input, extraArgs: args });
}

// Runs BibTeX over the .aux of the pass; returns true when a new .bbl was generated.
async function wasmBibtexStep(b, nowFiles, citeKey) {
  const { files, main, jobname, logs, helperFiles, sw } = b;
  let bibGenerated = false;
  updateStatus('saving', T('Generating the bibliography (BibTeX)...'));
  try {
    const bibInput = bibInputFor(files, nowFiles, main);
    const bib = await runBibtex(jobname, bibInput);
    logs.push(`\n===== BibTeX =====\n${bib.log}`);
    b.bibLogText = bib.log;
    sw.lap('BibTeX');
    b.usedCiteKey = citeKey;
    if (bib.bbl && bib.bbl.length) { helperFiles.set(jobname + '.bbl', bib.bbl); bibGenerated = true; }
  } catch (err) {
    logs.push(`\n===== BibTeX =====\nCould not run BibTeX: ${err.message}\nCitations will appear as [?].`);
  }
  return bibGenerated;
}

// Runs Biber over the .bcf of the pass; returns true when a new .bbl was generated.
async function wasmBiberStep(b, nowFiles, citeKey) {
  const { files, main, jobname, logs, helperFiles, sw } = b;
  let bibGenerated = false;
  updateStatus('saving', 'Generating the bibliography (Biber)... the first time it downloads about 23 MB');
  try {
    const bib = await runBiber(jobname, bibInputFor(files, nowFiles, main));
    logs.push(`\n===== Biber =====\n${bib.log}`);
    b.bibLogText = bib.log;
    sw.lap('Biber');
    b.usedCiteKey = citeKey;
    if (bib.bbl && bib.bbl.length) { helperFiles.set(jobname + '.bbl', bib.bbl); bibGenerated = true; }
  } catch (err) {
    logs.push(`\n===== Biber =====\nCould not run Biber: ${err.message}\nCitations will appear as [?]. Alternative: \\usepackage[backend=bibtex]{biblatex}.`);
  }
  return bibGenerated;
}

// Collects the timings and log, stores the build state for reuse and returns the compilation result object.
function wasmFinishBuild(b) {
  const { sw, prev, logs, lastPassLog, bibLogText, result, base, jobname, extra, helperFiles, fastOnly, buildKey, bibHash, main, findPdf } = b;
  const timing = sw.summary();
  console.info('[compilation]', timing);
  logs.push('\n===== Timings =====\n' + timing + (prev ? ' (reused the auxiliary files from the previous compilation)' : ''));
  const logText = logs.join('\n');
  const diagnostics = parseLogToDiagnostics(lastPassLog + '\n' + bibLogText);
  const pdfBytes = findPdf(result && result.outputs);
  const synctexBytes = result && (outputGet(result.outputs, base + '.synctex.gz') || outputGet(result.outputs, jobname + '.synctex.gz')) || null;

  if (pdfBytes && pdfBytes.length > 0) {
    const blob = new Blob([pdfBytes], { type: 'application/pdf' });
    const blobUrl = URL.createObjectURL(blob);
    // the citation key is the one of the FINAL .aux (the same the next compilation will receive), to reuse the .bbl already the first time
    const finalAux = extra.get(jobname + '.aux');
    if (!fastOnly) lastBuild = { key: buildKey, extra, bibHash, citeKey: finalAux && helperFiles.has(jobname + '.bbl') ? citeKeyOf(bytesToText(finalAux)) : b.usedCiteKey, bbl: helperFiles.get(jobname + '.bbl') || null };
    updateStatus('saved', fastOnly ? `Compiled in fast mode (only ${fastOnly})` : 'Compiled successfully' + (b.passes > 1 ? ` (${b.passes} passes)` : ''));
    return {
      success: true,
      blobUrl: blobUrl,
      pdfBytes: pdfBytes,
      synctexBytes: synctexBytes,
      bblBytes: helperFiles.get(jobname + '.bbl') || null,
      partial: fastOnly || null,
      mainFile: main,
      log: logText || 'texlive-wasm / BusyTeX compilation completed successfully.',
      diagnostics: diagnostics,
      engine_used: 'texlive-wasm / BusyTeX (WebAssembly)'
    };
  }
  if (!fastOnly) lastBuild = null;      // failed: the next one starts from scratch (fast mode does not touch the full compilation state)
  updateStatus('error', 'WebAssembly compilation error');
  return {
    success: false,
    blobUrl: null,
    log: logText || ('texlive-wasm compilation failed. Exit code: ' + (result && result.exitCode)),
    diagnostics: diagnostics,
    engine_used: 'texlive-wasm / BusyTeX (WebAssembly)'
  };
}

// Compiles locally in the browser with WebAssembly (texlive-wasm / BusyTeX)
async function compileWithWasm() {
  updateStatus('saving', 'Gathering the project files...');
  const sw = stopwatch();
  const { files, main } = await gatherProject();
  rememberTexts(files);
  sw.lap('projeto');
  const families = await familiesFor(files);
  const engine = await getTexliveEngine(families);
  updateStatus('saving', 'Compiling via texlive-wasm...');
  sw.lap('motor');

  const b = wasmBuildState(files, main, sw);
  const { fastOnly, jobname, prev, bibHash, logs, helperFiles, findPdf } = b;
  const MAX_PASSES = 6;      // with the fixed-point stop, the limit only matters for documents that take long to converge

  // Clean compilation of a document that has references, a table of contents or citations: the 1st pass only generates the auxiliary files (the 2nd is
  // certain). In -draftmode pdfTeX does everything the same (same pagination) but does not write the PDF or embed images and fonts: ~30% faster.
  // The draft pass would delay the preview (the first PDF would only come out on pass 2): we prefer to show pass 1 right away.
  const DRAFT_FIRST_PASS = false;
  let previewShown = false;
  const multiPass = /\\(?:tableofcontents|listoffigures|listoftables|label|ref|eqref|autoref|cref|pageref|nameref|cite[a-z]*|nocite|bibliography|printindex|makeindex|glossary)\b/;
  const needsMorePasses = [...files].some(([p, c]) => typeof c === 'string' && /\.(tex|cls|sty)$/i.test(p) && multiPass.test(c));

  for (let pass = 1; pass <= MAX_PASSES; pass++) {
    const draft = DRAFT_FIRST_PASS && pass === 1 && b.extra.size === 0 && needsMorePasses;
    const result = b.result = await wasmRunPass(b, engine, pass, draft);
    b.passes++;
    sw.lap('pass ' + pass + (draft ? ' (draft)' : ''));

    const logText = (result.log || '') + (result.stdout ? '\n' + result.stdout : '') + (result.stderr ? '\n' + result.stderr : '');
    logs.push(pass > 1 ? `\n===== Pass ${pass} =====\n${logText}` : logText);
    b.lastPassLog = logText;

    const pdf = findPdf(result.outputs);
    if (draft) {
      if ((result.exitCode && result.exitCode !== 0) || /Fatal error occurred|Emergency stop/.test(logText)) break;   // failed: show the log
    } else if (!pdf || !pdf.length) break;                // failed: show the log

    // this pass's auxiliary files (.aux, .toc, .out...) for the next one
    const nextExtra = new Map();
    for (const [path, content] of outputEntries(result.outputs)) {
      if (/\.(log|pdf|synctex\.gz|synctex)$/i.test(path)) continue;
      nextExtra.set(path, content);
    }

    // Preview: if another pass is coming (there is no baseline, or the auxiliary files changed), show this PDF right away (references and
    // table of contents may be out of date) while BibTeX and the remaining passes finish in the background.
    if (!previewShown && !fastOnly && pdf && pdf.length && (b.extra.size === 0 || !auxStable(nextExtra, b.extra))) { previewShown = true; showPreview(pdf); }

    // BibTeX: the .aux asks for a bibliography (\bibdata) and there are citations (\citation)
    let bibGenerated = false;
    // the engine only returns what changed: if the .aux did not come back, the previous pass's one stands
    const nowFiles = new Map([...b.extra, ...nextExtra]);
    const auxText = bytesToText(outputGet(result.outputs, jobname + '.aux') || nowFiles.get(jobname + '.aux'));
    const bcfBytes = outputGet(result.outputs, jobname + '.bcf') || nowFiles.get(jobname + '.bcf');
    const bcfText = bcfBytes ? bytesToText(bcfBytes) : '';
    const wantsBiber = biberWanted(bcfText, auxText);
    const citeKey = wantsBiber ? 'biber:' + hashFiles(new Map([['bcf', bcfText]]), /./) : citeKeyOf(auxText);
    const reuseBbl = helperFiles.has(jobname + '.bbl') && (fastOnly || !!(prev && prev.bibHash === bibHash && prev.citeKey === citeKey));
    if (!b.bibtexRan && reuseBbl) { b.bibtexRan = true; b.usedCiteKey = citeKey; sw.lap('BibTeX reaproveitado'); }
    if (!b.bibtexRan && /\\bibdata\{/.test(auxText) && /\\citation\{/.test(auxText)) {
      b.bibtexRan = true;
      bibGenerated = await wasmBibtexStep(b, nowFiles, citeKey);
    }

    // Biber: the .bcf asks for the bibliography (biblatex with the default backend)
    if (!b.bibtexRan && wantsBiber) {
      b.bibtexRan = true;
      bibGenerated = await wasmBiberStep(b, nowFiles, citeKey);
    }

    // fixed point: this pass's auxiliary files equal those it received, so another pass would change nothing
    const stable = b.extra.size > 0 && auxStable(nextExtra, b.extra);
    if (!stable) { const ch = auxChanged(nextExtra, b.extra); sw.lap('changed: ' + ch.slice(0, 6).join(', ') + (ch.length > 6 ? ` (+${ch.length - 6})` : '')); }

    // pdflatex only returns what changed: the .bbl (input) has to be resent on every pass
    // accumulates: the engine does not return what did not change, but the next pass still needs those files (.toc, .out...)
    const merged = new Map(b.extra);
    for (const [path, content] of nextExtra) merged.set(path, content);
    for (const [path, content] of helperFiles) merged.set(path, content);
    b.extra = merged;
    if (draft) continue;                                  // the draft pass is never the last one: there is no PDF yet
    const done = (stable && !bibGenerated) || pass === MAX_PASSES || (!bibGenerated && !RERUN_RE.test(result.log || logText));
    if (done) { if (stable && !bibGenerated) logs.push(`\n(auxiliary files stable: stopped at pass ${pass})`); break; }
  }

  return wasmFinishBuild(b);
}
